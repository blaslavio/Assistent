def _norm(tekst):
    return "".join(c for c in unicodedata.normalize("NFKD", tekst.casefold()) if not unicodedata.combining(c))


def catalogus(online: bool, uit=(), niveau="particulier") -> list[dict]:
    uit = set(uit)
    resultaat = []
    for t in TOOLS:
        redenen = []
        if t["online"] and not online:
            redenen.append("Vereist een online account.")
        if any(m in uit for m in t["modules"]):
            redenen.append("Dit onderdeel staat uit bij Weergave.")
        if t["een_van"] and all(m in uit for m in t["een_van"]):
            redenen.append("Alle bijbehorende onderdelen staan uit bij Weergave.")
        if t["rollen"] and niveau not in t["rollen"]:
            redenen.append("Vereist accounttype verkoper of ondernemer.")
        resultaat.append({**copy.deepcopy(t), "beschikbaar": not redenen, "redenen": redenen})
    return resultaat


def paginanamen() -> dict[str, str]:
    return {**KERN, **{t["url"]: t["titel"] for t in TOOLS}}


def zoek(lijst, tekst="", groep=None, alleen_beschikbaar=False):
    if not isinstance(tekst, str) or len(tekst) > 160:
        raise ValueError("Gebruik maximaal 160 tekens.")
    termen = _norm(tekst).split()
    return [t for t in lijst if (not groep or t["groep"] == groep)
            and (not alleen_beschikbaar or t["beschikbaar"])
            and all(w in _norm(t["titel"] + " " + t["groep"] + " " + t["url"]) for w in termen)]


def dekking(lijst, paginas) -> list[dict]:
    actief = set(paginas)
    return [{"map": g, "eigen_tools": sum(t["groep"] == g for t in lijst),
             "beschikbaar": sum(t["groep"] == g and t["url"] in actief for t in lijst),
             "gedeeld": [u for u in GEDEELD[g] if u in actief],
             "status": "beschikbaar" if any(t["groep"] == g and t["url"] in actief for t in lijst) else "gedeelde hulpmiddelen" if any(u in actief for u in GEDEELD[g]) else "niet beschikbaar"}
            for g in GROEPEN]
