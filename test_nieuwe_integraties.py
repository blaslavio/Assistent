"""Nieuwe databasegrenzen op een eigen PostgreSQL-database, nooit productie."""
import json
import os
from pathlib import Path
import subprocess
import unittest
import uuid


@unittest.skipUnless(os.environ.get("ASSISTENT_TEST_POSTGRES_CONTAINER"), "Eigen PostgreSQL-container vereist")
class NieuweIntegratieTests(unittest.TestCase):
    @classmethod
    def sql(cls, tekst, database=None):
        env = {k:v for k,v in os.environ.items() if k not in {"DOCKER_HOST","DOCKER_CONTEXT","DOCKER_TLS","DOCKER_TLS_VERIFY","DOCKER_CERT_PATH"}}
        r = subprocess.run(["docker","--host=unix:///var/run/docker.sock","exec","-i",os.environ["ASSISTENT_TEST_POSTGRES_CONTAINER"],
            "psql","-U","postgres","-d",database or cls.database,"-XqAt","-v","ON_ERROR_STOP=1"],input=tekst,text=True,capture_output=True,env=env,check=True,timeout=20)
        return r.stdout.strip()

    @classmethod
    def setUpClass(cls):
        cls.database="nieuwe_integraties_"+uuid.uuid4().hex
        cls.sql(f'create database "{cls.database}"',"postgres")
        cls.addClassCleanup(lambda:cls.sql(f'drop database "{cls.database}" with(force)',"postgres"))
        cls.sql("""
          do $$ begin if not exists(select from pg_roles where rolname='anon') then create role anon; end if;
          if not exists(select from pg_roles where rolname='authenticated') then create role authenticated; end if; end $$;
          create schema private; create schema auth; create schema extensions;
          create extension pgcrypto with schema extensions;
          create table private.gebruikers(id bigint generated by default as identity primary key, naam text unique, email text,
            weergavenaam text, hash text, akkoord_op timestamptz, aangemaakt timestamptz default now(),
            totp_aan boolean default false, geblokkeerd boolean default false, verwijderd boolean default false);
          create table private.inlogs(gebruiker bigint,apparaat text,gelukt boolean,reden text);
          create table public.gegevens(id bigint primary key,data jsonb);
          create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz);
          create function auth.jwt() returns jsonb language sql as $$ select coalesce(nullif(current_setting('test.jwt',true),''),'{}')::jsonb $$;
          create function auth.uid() returns uuid language sql as $$ select (auth.jwt()->>'sub')::uuid $$;
          create function private.nieuwe_sessie(bigint,text) returns text language sql as $$ select 'test-session-'||$1::text $$;
          create function private.gebruiker_id(text,text) returns bigint language sql as $$ select id from private.gebruikers where naam=$1 and $2='test-only' and not geblokkeerd and not verwijderd $$;
          create table private.winkels(gebruiker_id bigint primary key references private.gebruikers(id),adres text unique,open boolean default false);
          create table private.community_activiteiten(id bigint primary key,community bigint,weg boolean default false,titel text,start timestamptz,einde timestamptz);
          create table private.chat_communities(id bigint primary key,weg boolean default false,herinnering boolean default false);
          create table private.leden(gebruiker bigint,community bigint);
          create function private.chat_community_rol(bigint,bigint) returns text language sql as $$ select 'lid'::text from private.leden where gebruiker=$1 and community=$2 $$;
          create function private.ca_activiteit_json(private.community_activiteiten,bigint) returns jsonb language sql as $$ select jsonb_build_object('id',($1).id,'titel',($1).titel) $$;
        """)
        for name in ("extern_inloggen.sql","winkel_contact.sql","evenementpagina.sql"):
            cls.sql((Path(__file__).parent/"sql"/name).read_text())

    def setUp(self):
        self.sql("""truncate private.winkel_contact,private.winkels,private.inlogs,public.gegevens,auth.users,private.leden,private.chat_communities,private.community_activiteiten,private.gebruikers restart identity cascade;
          insert into private.gebruikers(naam,email) values('alice','alice@example.org'),('bob','bob@example.org');
          insert into private.winkels values(1,'alice-shop',true),(2,'bob-shop',false);
          insert into private.leden values(1,10); insert into private.chat_communities(id) values(10);
          insert into private.community_activiteiten(id,community,titel,start,einde) values(100,10,'Groepsfeest','2030-01-01T10:00Z','2030-01-01T12:00Z');
        """)

    def extern(self, provider="google", confirmed=True, akkoord=True, metadata=None):
        jwt={"sub":"00000000-0000-4000-8000-000000000001","app_metadata":{"provider":provider},"user_metadata":metadata or {"email_verified":True}}
        self.sql("insert into auth.users values('00000000-0000-4000-8000-000000000001','alice@example.org',"+("now()" if confirmed else "null")+")")
        q=json.dumps(jwt).replace("'","''")
        return json.loads(self.sql(f"select set_config('test.jwt','{q}',false); select public.inloggen_extern('Testbrowser',{'true' if akkoord else 'false'});").splitlines()[-1])

    def test_verified_identity_can_link_existing_account(self):
        self.assertEqual(self.extern()["naam"],"alice")
        self.assertEqual(self.sql("select count(*) from private.inlogs"),"1")

    def test_user_metadata_cannot_verify_email(self):
        self.assertIn("fout",self.extern(confirmed=False,metadata={"email_verified":True}))
        self.assertEqual(self.sql("select count(*) from private.gebruikers where auth_id is not null"),"0")

    def test_linked_two_factor_account_cannot_bypass_code(self):
        self.sql("update private.gebruikers set totp_aan=true,auth_id='00000000-0000-4000-8000-000000000001' where id=1")
        self.assertIn("fout",self.extern())
        self.assertEqual(self.sql("select count(*) from private.inlogs"),"0")

    def test_unknown_provider_is_rejected(self):
        self.assertIn("fout",self.extern(provider="email"))
        self.assertEqual(self.sql("select count(*) from private.inlogs"),"0")

    def test_new_external_account_requires_consent(self):
        self.sql("update private.gebruikers set email='other@example.org' where id=1")
        self.assertIn("fout",self.extern(akkoord=False))
        self.assertEqual(self.sql("select count(*) from private.gebruikers"),"2")

    def test_verified_new_external_account_can_be_created(self):
        self.sql("update private.gebruikers set email='other@example.org' where id=1")
        self.assertIn("token",self.extern(akkoord=True))
        self.assertEqual(self.sql("select count(*) from private.gebruikers"),"3")

    def test_anon_cannot_call_external_session_endpoint(self):
        with self.assertRaises(subprocess.CalledProcessError):
            self.sql("set role anon; select public.inloggen_extern('Browser',true)")

    def save_contact(self, naam="alice", **changes):
        v={"chat":False,"email":"shop@example.org","telefoon":"","whatsapp":"","website":"","betaalwijzen":["contant"]}
        v.update(changes)
        q=json.dumps(v).replace("'","''")
        return json.loads(self.sql(f"select public.winkel_contact_bewaren('{naam}','test-only','{q}'::jsonb)"))

    def test_public_contact_only_contains_explicit_channels(self):
        self.assertTrue(self.save_contact()["ok"])
        r=json.loads(self.sql("select public.winkel_contact_bekijken('alice-shop')"))
        self.assertEqual(r["contact"]["email"],"shop@example.org")
        self.assertIsNone(r["gebruiker"])
        self.assertEqual(r["contact"]["telefoon"],"")

    def test_closed_shop_and_other_owner_remain_private(self):
        self.save_contact(naam="bob")
        self.assertEqual(self.sql("select public.winkel_contact_bekijken('bob-shop')"),"")
        self.assertEqual(json.loads(self.sql("select public.mijn_winkel_contact('alice','test-only')"))["contact"],{})

    def test_unsafe_links_unknown_payments_and_missing_channels_are_rejected(self):
        for changes in ({"website":"javascript:alert(1)"},{"website":"https://user:pass@example.org"},{"chat":None},{"betaalwijzen":["onbekend"]},{"email":""}):
            with self.subTest(changes=changes): self.assertIn("fout",self.save_contact(**changes))

    def test_account_removal_clears_new_contact_data(self):
        self.save_contact()
        self.sql("update private.gebruikers set verwijderd=true where id=1")
        self.assertEqual(self.sql("select count(*) from private.winkel_contact"),"0")

    def test_raw_contact_table_is_not_readable(self):
        with self.assertRaises(subprocess.CalledProcessError): self.sql("set role anon; select * from private.winkel_contact")

    def test_event_page_requires_current_membership_and_hides_deleted_events(self):
        r=json.loads(self.sql("select public.community_evenement_bekijken('alice','test-only',10,100)"))
        self.assertEqual(r["activiteit"]["titel"],"Groepsfeest")
        self.assertIn("fout",json.loads(self.sql("select public.community_evenement_bekijken('bob','test-only',10,100)")))
        self.sql("update private.community_activiteiten set weg=true where id=100")
        self.assertIn("fout",json.loads(self.sql("select public.community_evenement_bekijken('alice','test-only',10,100)")))

    def test_server_rejects_event_without_end_or_with_reversed_time(self):
        for end in (None,"2030-01-01T09:00Z","2030-01-01T10:00Z"):
            v=json.dumps({"soort":"evenement","titel":"Feest","start":"2030-01-01T10:00Z","einde":end})
            r=json.loads(self.sql(f"select public.community_activiteit_bewaren('alice','test-only',10,null,'{v}',0)"))
            self.assertIn("fout",r)
