      'tekst', b.tekst, 'gelezen', b.gelezen or b.van = v_id, 'aangemaakt', b.aangemaakt) order by b.id)
    from (select * from private.berichten where van = v_id or aan = v_id order by id desc limit 300) b
    join private.aanbod a on a.id = b.aanbod_id), '[]'::jsonb));
end; $$;

