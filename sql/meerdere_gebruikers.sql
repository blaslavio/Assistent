create or replace function public.beheer_meldingen(p_naam text, p_wachtwoord text)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord);
begin
  if v_id is distinct from 1 then return jsonb_build_object('geen_toegang', true); end if;
  return jsonb_build_object(
    'meldingen', coalesce((
      select jsonb_agg(jsonb_build_object('id', m.id, 'reden', m.reden, 'door', private.weergave(m.door),
                                          'aangemaakt', m.aangemaakt, 'aanbod', private.aanbod_json(a, v_id)) order by m.id)
      from private.meldingen m join private.aanbod a on a.id = m.aanbod_id where not m.afgehandeld), '[]'::jsonb),
    'gebruikers', (select count(*) from private.gebruikers where not verwijderd),
    'aanbod', (select count(*) from private.aanbod where actief and not geblokkeerd));
end; $$;

create or replace function public.beheer_afhandelen(p_naam text, p_wachtwoord text, p_melding bigint,
                                                    p_aanbod_blokkeren boolean, p_aanbieder_blokkeren boolean)
returns boolean language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord); v_aanbod bigint; v_aanbieder bigint;
begin
  if v_id is distinct from 1 then return false; end if;
  update private.meldingen set afgehandeld = true where id = p_melding returning aanbod_id into v_aanbod;
  if v_aanbod is null then return false; end if;
  if p_aanbod_blokkeren then update private.aanbod set geblokkeerd = true where id = v_aanbod; end if;
  if p_aanbieder_blokkeren then
    select gebruiker_id into v_aanbieder from private.aanbod where id = v_aanbod;
    update private.gebruikers set geblokkeerd = true where id = v_aanbieder and id <> 1;
    update private.aanbod set actief = false where gebruiker_id = v_aanbieder;
  end if;
  return true;
end; $$;

