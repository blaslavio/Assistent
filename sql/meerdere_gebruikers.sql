    select jsonb_agg(jsonb_build_object(
      'id', b.id, 'aanbod_id', b.aanbod_id, 'titel', a.titel, 'van_mij', b.van = v_id,
      'ander_id', case when b.van = v_id then b.aan else b.van end,
