create or replace function public.tijdslot_toevoegen(p_naam text, p_wachtwoord text, p_aanbod bigint,
                                                     p_start timestamptz, p_minuten integer)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord);
begin
  if v_id is null then return jsonb_build_object('geen_toegang', true); end if;
  if not exists (select 1 from private.aanbod where id = p_aanbod and gebruiker_id = v_id) then
    return jsonb_build_object('fout', 'Dit aanbod is niet van jou.');
  end if;
  if p_start < now() then return jsonb_build_object('fout', 'Kies een tijd in de toekomst.'); end if;
  if exists (select 1 from private.tijdsloten t join private.aanbod a on a.id = t.aanbod_id
             where a.gebruiker_id = v_id and not t.geannuleerd
               and tstzrange(t.start, t.start + make_interval(mins => t.minuten))
                   && tstzrange(p_start, p_start + make_interval(mins => p_minuten))) then
    return jsonb_build_object('fout', 'Je hebt op dat moment al een tijd staan.');
  end if;
  insert into private.tijdsloten (aanbod_id, start, minuten) values (p_aanbod, p_start, p_minuten);
  return jsonb_build_object('ok', true);
end; $$;

create or replace function public.tijdsloten(p_naam text, p_wachtwoord text, p_aanbod bigint)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord); v_eigen boolean;
begin
  if v_id is null then return jsonb_build_object('geen_toegang', true); end if;
  v_eigen := exists (select 1 from private.aanbod where id = p_aanbod and gebruiker_id = v_id);
  return jsonb_build_object('tijden', coalesce((
    select jsonb_agg(jsonb_build_object(
      'id', t.id, 'start', t.start, 'minuten', t.minuten, 'vrij', t.geboekt_door is null,
      'door_mij', coalesce(t.geboekt_door = v_id, false),
      'klant', case when v_eigen and t.geboekt_door is not null then private.weergave(t.geboekt_door) end,
      'opmerking', case when v_eigen or t.geboekt_door = v_id then t.opmerking end) order by t.start)
    from private.tijdsloten t
    where t.aanbod_id = p_aanbod and not t.geannuleerd and t.start > now()
      and (v_eigen or t.geboekt_door is null or t.geboekt_door = v_id)), '[]'::jsonb));
end; $$;

create or replace function public.boeken(p_naam text, p_wachtwoord text, p_tijdslot bigint, p_opmerking text)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord); v_rij record;
begin
  if v_id is null then return jsonb_build_object('geen_toegang', true); end if;
  update private.tijdsloten t set geboekt_door = v_id, geboekt_op = now(), opmerking = left(coalesce(p_opmerking, ''), 1000)
  from private.aanbod a
  where t.id = p_tijdslot and a.id = t.aanbod_id and a.actief and not a.geblokkeerd and a.gebruiker_id <> v_id
    and t.geboekt_door is null and not t.geannuleerd and t.start > now()
  returning t.start, t.minuten, a.titel, a.plaats, a.id as aanbod_id, a.gebruiker_id into v_rij;
  if not found then return jsonb_build_object('fout', 'Deze tijd is niet meer beschikbaar.'); end if;
  insert into private.berichten (aanbod_id, van, aan, tekst)
  values (v_rij.aanbod_id, v_id, v_rij.gebruiker_id,
          'Ik heb geboekt op ' || to_char(v_rij.start at time zone 'Europe/Amsterdam', 'DD-MM-YYYY HH24:MI') ||
          case when coalesce(p_opmerking, '') <> '' then '. ' || p_opmerking else '' end);
  return jsonb_build_object('ok', true, 'titel', v_rij.titel, 'start', v_rij.start, 'minuten', v_rij.minuten,
                            'plaats', v_rij.plaats, 'aanbieder', private.weergave(v_rij.gebruiker_id));
end; $$;

create or replace function public.boeking_annuleren(p_naam text, p_wachtwoord text, p_tijdslot bigint)
returns boolean language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord);
begin
  if v_id is null then return false; end if;
  -- Klant annuleert: de tijd komt weer vrij. Aanbieder annuleert: de tijd vervalt.
  update private.tijdsloten set geboekt_door = null, geboekt_op = null, opmerking = ''
  where id = p_tijdslot and geboekt_door = v_id;
  if found then return true; end if;
  update private.tijdsloten t set geannuleerd = true
  from private.aanbod a where t.id = p_tijdslot and a.id = t.aanbod_id and a.gebruiker_id = v_id;
  return found;
end; $$;

create or replace function public.mijn_boekingen(p_naam text, p_wachtwoord text)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord);
begin
  if v_id is null then return jsonb_build_object('geen_toegang', true); end if;
  return jsonb_build_object('boekingen', coalesce((
    select jsonb_agg(jsonb_build_object(
      'id', t.id, 'start', t.start, 'minuten', t.minuten, 'titel', a.titel, 'plaats', a.plaats,
      'rol', case when t.geboekt_door = v_id then 'klant' else 'aanbieder' end,
      'met', private.weergave(case when t.geboekt_door = v_id then a.gebruiker_id else t.geboekt_door end),
      'opmerking', t.opmerking) order by t.start)
    from private.tijdsloten t join private.aanbod a on a.id = t.aanbod_id
    where not t.geannuleerd and t.geboekt_door is not null and t.start > now() - interval '1 day'
      and (t.geboekt_door = v_id or a.gebruiker_id = v_id)), '[]'::jsonb));
end; $$;

create or replace function public.bericht_sturen(p_naam text, p_wachtwoord text, p_aanbod bigint, p_aan bigint, p_tekst text)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord); v_aan bigint;
begin
  if v_id is null then return jsonb_build_object('geen_toegang', true); end if;
  if trim(coalesce(p_tekst, '')) = '' then return jsonb_build_object('fout', 'Schrijf een bericht.'); end if;
  select case when gebruiker_id = v_id then p_aan else gebruiker_id end into v_aan
  from private.aanbod where id = p_aanbod and not geblokkeerd;
  if v_aan is null or v_aan = v_id then return jsonb_build_object('fout', 'Ontvanger niet gevonden.'); end if;
  if (select count(*) from private.berichten where van = v_id and aangemaakt > now() - interval '1 hour') >= 60 then
    return jsonb_build_object('fout', 'Je stuurt erg veel berichten. Probeer het later opnieuw.');
  end if;
  insert into private.berichten (aanbod_id, van, aan, tekst) values (p_aanbod, v_id, v_aan, left(trim(p_tekst), 2000));
  return jsonb_build_object('ok', true);
end; $$;

