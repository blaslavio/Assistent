  return jsonb_build_object('aanbod', coalesce((
    select jsonb_agg(private.aanbod_json(a, v_id) order by a.aangemaakt desc)
    from (select * from private.aanbod a
          where a.actief and not a.geblokkeerd
            and (coalesce(p_soort, '') = '' or a.soort = p_soort)
            and (coalesce(p_zoekterm, '') = '' or a.titel ilike '%' || p_zoekterm || '%'
                 or a.omschrijving ilike '%' || p_zoekterm || '%' or a.plaats ilike '%' || p_zoekterm || '%')
            and exists (select 1 from private.gebruikers g where g.id = a.gebruiker_id and not g.geblokkeerd and not g.verwijderd)
          order by a.aangemaakt desc limit 100) a), '[]'::jsonb));
end; $$;

