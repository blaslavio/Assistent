  return found;
end; $$;

-- --- Delen met een andere gebruiker -------------------------------------------

create table private.gedeeld (
  id bigint generated always as identity primary key,
  van bigint not null references private.gebruikers(id),
  aan bigint not null references private.gebruikers(id),
  soort text not null check (soort in ('afspraak', 'taak', 'boodschappen', 'notitie')),
  inhoud jsonb not null,
  status text not null default 'nieuw' check (status in ('nieuw', 'aangenomen', 'afgewezen')),
  aangemaakt timestamptz not null default now()
);

create or replace function public.delen(p_naam text, p_wachtwoord text, p_aan text, p_soort text, p_inhoud jsonb)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord); v_aan bigint;
begin
  if v_id is null then return jsonb_build_object('geen_toegang', true); end if;
  select id into v_aan from private.gebruikers
  where naam = lower(trim(p_aan)) and not verwijderd and not geblokkeerd;
  if v_aan is null then return jsonb_build_object('fout', 'Geen gebruiker met die naam.'); end if;
  if v_aan = v_id then return jsonb_build_object('fout', 'Dat ben je zelf.'); end if;
  if (select count(*) from private.gedeeld where van = v_id and aangemaakt > now() - interval '1 hour') >= 60 then
    return jsonb_build_object('fout', 'Je deelt erg veel. Probeer het later opnieuw.');
  end if;
  insert into private.gedeeld (van, aan, soort, inhoud) values (v_id, v_aan, p_soort, p_inhoud);
  return jsonb_build_object('ok', true, 'aan', private.weergave(v_aan));
end; $$;

create or replace function public.gedeeld_met_mij(p_naam text, p_wachtwoord text)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord);
begin
  if v_id is null then return jsonb_build_object('geen_toegang', true); end if;
  return jsonb_build_object('gedeeld', coalesce((
    select jsonb_agg(jsonb_build_object('id', id, 'van', private.weergave(van), 'soort', soort, 'inhoud', inhoud,
                                        'aangemaakt', aangemaakt) order by id desc)
    from private.gedeeld where aan = v_id and status = 'nieuw'), '[]'::jsonb));
end; $$;

create or replace function public.gedeeld_afhandelen(p_naam text, p_wachtwoord text, p_id bigint, p_aangenomen boolean)
returns boolean language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord);
begin
  if v_id is null then return false; end if;
  update private.gedeeld set status = case when p_aangenomen then 'aangenomen' else 'afgewezen' end
  where id = p_id and aan = v_id and status = 'nieuw';
  return found;
end; $$;

-- --- Samen werken aan een project ---------------------------------------------

create table private.projecten (
  id bigint generated always as identity primary key,
  naam text not null,
  omschrijving text not null default '',
  eigenaar bigint not null references private.gebruikers(id),
  gearchiveerd boolean not null default false,
  aangemaakt timestamptz not null default now()
);

create table private.project_leden (
  project_id bigint not null references private.projecten(id),
  gebruiker_id bigint not null references private.gebruikers(id),
  actief boolean not null default true,
  sinds timestamptz not null default now(),
  primary key (project_id, gebruiker_id)
);

create table private.project_items (
  id bigint generated always as identity primary key,
  project_id bigint not null references private.projecten(id),
  soort text not null check (soort in ('taak', 'notitie', 'afspraak', 'link')),
  titel text not null,
  inhoud text not null default '',
  datum text not null default '',
  toegewezen_aan bigint references private.gebruikers(id),
  klaar boolean not null default false,
  verwijderd boolean not null default false,
  door bigint not null references private.gebruikers(id),
  aangemaakt timestamptz not null default now(),
  bijgewerkt timestamptz not null default now()
);

create or replace function private.is_lid(p_project bigint, p_gebruiker bigint)
returns boolean language sql stable security definer set search_path to '' as $$
  select exists (select 1 from private.project_leden l join private.projecten p on p.id = l.project_id
                 where l.project_id = p_project and l.gebruiker_id = p_gebruiker and l.actief and not p.gearchiveerd)
$$;

create or replace function public.projecten(p_naam text, p_wachtwoord text)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord);
begin
  if v_id is null then return jsonb_build_object('geen_toegang', true); end if;
  return jsonb_build_object('projecten', coalesce((
    select jsonb_agg(jsonb_build_object(
      'id', p.id, 'naam', p.naam, 'omschrijving', p.omschrijving, 'eigenaar', private.weergave(p.eigenaar),
      'ik_ben_eigenaar', p.eigenaar = v_id,
      'leden', (select jsonb_agg(jsonb_build_object('naam', g.naam, 'weergavenaam', private.weergave(g.id)) order by l2.sinds)
                from private.project_leden l2 join private.gebruikers g on g.id = l2.gebruiker_id
                where l2.project_id = p.id and l2.actief),
      'open', (select count(*) from private.project_items i
               where i.project_id = p.id and not i.verwijderd and not i.klaar and i.soort in ('taak', 'afspraak')))
      order by p.id desc)
    from private.projecten p join private.project_leden l on l.project_id = p.id
    where l.gebruiker_id = v_id and l.actief and not p.gearchiveerd), '[]'::jsonb));
end; $$;

create or replace function public.project_maken(p_naam text, p_wachtwoord text, p_titel text, p_omschrijving text)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord); v_project bigint;
begin
  if v_id is null then return jsonb_build_object('geen_toegang', true); end if;
  if trim(coalesce(p_titel, '')) = '' then return jsonb_build_object('fout', 'Geef het project een naam.'); end if;
  insert into private.projecten (naam, omschrijving, eigenaar)
  values (left(trim(p_titel), 100), left(coalesce(p_omschrijving, ''), 2000), v_id) returning id into v_project;
  insert into private.project_leden (project_id, gebruiker_id) values (v_project, v_id);
  return jsonb_build_object('ok', true, 'id', v_project);
end; $$;

create or replace function public.project_lid_toevoegen(p_naam text, p_wachtwoord text, p_project bigint, p_gebruikersnaam text)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord); v_lid bigint;
begin
  if v_id is null then return jsonb_build_object('geen_toegang', true); end if;
  if not private.is_lid(p_project, v_id) then return jsonb_build_object('fout', 'Je bent geen lid van dit project.'); end if;
  select id into v_lid from private.gebruikers
  where naam = lower(trim(p_gebruikersnaam)) and not verwijderd and not geblokkeerd;
  if v_lid is null then return jsonb_build_object('fout', 'Geen gebruiker met die naam.'); end if;
  insert into private.project_leden (project_id, gebruiker_id) values (p_project, v_lid)
  on conflict (project_id, gebruiker_id) do update set actief = true;
  return jsonb_build_object('ok', true, 'lid', private.weergave(v_lid));
end; $$;

create or replace function public.project_verlaten(p_naam text, p_wachtwoord text, p_project bigint)
returns boolean language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord);
begin
  if v_id is null then return false; end if;
  update private.project_leden set actief = false where project_id = p_project and gebruiker_id = v_id;
  -- Verlaat de eigenaar het project, dan wordt het gearchiveerd als er niemand meer in zit.
  update private.projecten set gearchiveerd = true
  where id = p_project and not exists (select 1 from private.project_leden where project_id = p_project and actief);
  return true;
end; $$;

create or replace function public.project_items(p_naam text, p_wachtwoord text, p_project bigint)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord);
begin
  if v_id is null then return jsonb_build_object('geen_toegang', true); end if;
  if not private.is_lid(p_project, v_id) then return jsonb_build_object('fout', 'Je bent geen lid van dit project.'); end if;
  return jsonb_build_object('items', coalesce((
    select jsonb_agg(jsonb_build_object(
      'id', id, 'soort', soort, 'titel', titel, 'inhoud', inhoud, 'datum', datum, 'klaar', klaar,
      'door', private.weergave(door),
      'toegewezen_aan', case when toegewezen_aan is null then null else private.weergave(toegewezen_aan) end,
      'bijgewerkt', bijgewerkt) order by klaar, nullif(datum, '') nulls last, id)
    from private.project_items where project_id = p_project and not verwijderd), '[]'::jsonb));
end; $$;

create or replace function public.project_item_toevoegen(p_naam text, p_wachtwoord text, p_project bigint, p_soort text,
                                                         p_titel text, p_inhoud text, p_datum text, p_toegewezen_aan text)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord); v_aan bigint; v_item bigint;
begin
  if v_id is null then return jsonb_build_object('geen_toegang', true); end if;
  if not private.is_lid(p_project, v_id) then return jsonb_build_object('fout', 'Je bent geen lid van dit project.'); end if;
  if trim(coalesce(p_titel, '')) = '' then return jsonb_build_object('fout', 'Vul een titel in.'); end if;
  if coalesce(p_toegewezen_aan, '') <> '' then
    select g.id into v_aan from private.gebruikers g
    where g.naam = lower(trim(p_toegewezen_aan)) and private.is_lid(p_project, g.id);
  end if;
  insert into private.project_items (project_id, soort, titel, inhoud, datum, toegewezen_aan, door)
  values (p_project, coalesce(p_soort, 'taak'), left(trim(p_titel), 200), left(coalesce(p_inhoud, ''), 5000),
          coalesce(p_datum, ''), v_aan, v_id)
  returning id into v_item;
  return jsonb_build_object('ok', true, 'id', v_item);
end; $$;

create or replace function public.project_item_bijwerken(p_naam text, p_wachtwoord text, p_item bigint, p_klaar boolean,
                                                         p_titel text, p_inhoud text, p_verwijderd boolean)
returns boolean language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord);
begin
  if v_id is null then return false; end if;
  update private.project_items i set
    klaar = coalesce(p_klaar, i.klaar),
    titel = coalesce(nullif(trim(p_titel), ''), i.titel),
    inhoud = coalesce(p_inhoud, i.inhoud),
    verwijderd = coalesce(p_verwijderd, i.verwijderd),
    bijgewerkt = now()
  where i.id = p_item and private.is_lid(i.project_id, v_id);
  return found;
end; $$;

