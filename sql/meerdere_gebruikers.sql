  start timestamptz not null,
  minuten integer not null check (minuten between 5 and 1440),
  geboekt_door bigint references private.gebruikers(id),
  geboekt_op timestamptz,
  opmerking text not null default '',
  geannuleerd boolean not null default false
);

create table private.berichten (
  id bigint generated always as identity primary key,
  aanbod_id bigint not null references private.aanbod(id),
  van bigint not null references private.gebruikers(id),
  aan bigint not null references private.gebruikers(id),
  tekst text not null,
  gelezen boolean not null default false,
  aangemaakt timestamptz not null default now()
);

create table private.meldingen (
  id bigint generated always as identity primary key,
  aanbod_id bigint not null references private.aanbod(id),
  door bigint not null references private.gebruikers(id),
  reden text not null,
  afgehandeld boolean not null default false,
  aangemaakt timestamptz not null default now()
