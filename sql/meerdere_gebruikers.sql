-- Meerdere gebruikers, delen, samen werken aan projecten en een marktplaats.
-- Alles loopt via functies die naam + wachtwoord controleren; de tabellen in
-- het schema private zijn niet bereikbaar via de API.

-- --- Gebruikers -------------------------------------------------------------

create table private.gebruikers (
  id bigint generated by default as identity primary key,
  naam text unique check (naam ~ '^[a-z0-9_.-]{3,30}$'),
  weergavenaam text not null default '',
  hash text not null,
  akkoord_op timestamptz,
  geblokkeerd boolean not null default false,
  verwijderd boolean not null default false,
  aangemaakt timestamptz not null default now()
);

-- De huidige eigenaar wordt gebruiker 1 en houdt zijn gegevens (rij 1).
insert into private.gebruikers (id, naam, weergavenaam, hash, akkoord_op)
select 1, null, 'Eigenaar', hash, now() from private.wachtwoord limit 1;
select setval(pg_get_serial_sequence('private.gebruikers', 'id'),
              greatest(1, (select coalesce(max(id), 1) from private.gebruikers)));

alter table private.pogingen add column if not exists naam text;
alter table private.media add column if not exists gebruiker_id bigint not null default 1;

-- Geeft het id van de gebruiker als naam en wachtwoord kloppen, anders null.
-- Lege naam = de eigenaar (zo blijft zijn oude manier van inloggen werken).
create or replace function private.gebruiker_id(p_naam text, p_wachtwoord text)
returns bigint language plpgsql security definer set search_path to '' as $$
declare
  v_naam text := nullif(lower(trim(coalesce(p_naam, ''))), '');
  v_id bigint;
begin
  if (select count(*) from private.pogingen
      where tijd > now() - interval '15 minutes' and coalesce(naam, '') = coalesce(v_naam, '')) >= 10 then
    return null;
  end if;
  select id into v_id from private.gebruikers
  where (case when v_naam is null then id = 1 else naam = v_naam end)
    and not geblokkeerd and not verwijderd
    and hash = extensions.crypt(coalesce(p_wachtwoord, ''), hash);
  if v_id is null then
    insert into private.pogingen (naam) values (v_naam);
  end if;
  return v_id;
end; $$;

create or replace function private.weergave(p_id bigint)
returns text language sql stable security definer set search_path to '' as $$
  select coalesce(nullif(weergavenaam, ''), naam, 'Gebruiker ' || id) from private.gebruikers where id = p_id
$$;

create or replace function public.is_geregistreerd()
returns boolean language sql security definer set search_path to '' as $$
  select exists (select 1 from private.gebruikers where id = 1)
$$;

-- Eerste installatie: de eigenaar.
create or replace function public.registreer(p_wachtwoord text)
returns boolean language plpgsql security definer set search_path to '' as $$
begin
  if exists (select 1 from private.gebruikers where id = 1) or length(p_wachtwoord) < 10 then
    return false;
  end if;
  insert into private.gebruikers (id, weergavenaam, hash, akkoord_op)
  values (1, 'Eigenaar', extensions.crypt(p_wachtwoord, extensions.gen_salt('bf', 10)), now());
  return true;
end; $$;

-- Iedereen kan een account maken. Maximaal 30 nieuwe accounts per uur, tegen misbruik.
create or replace function public.account_maken(p_naam text, p_weergavenaam text, p_wachtwoord text, p_akkoord boolean)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare
  v_naam text := lower(trim(coalesce(p_naam, '')));
  v_id bigint;
begin
  if not coalesce(p_akkoord, false) then
    return jsonb_build_object('fout', 'Ga akkoord met de voorwaarden en de privacyverklaring.');
  end if;
  if v_naam !~ '^[a-z0-9_.-]{3,30}$' then
    return jsonb_build_object('fout', 'Kies een gebruikersnaam van 3 tot 30 tekens: kleine letters, cijfers, punt, streepje of laag streepje.');
  end if;
  if length(coalesce(p_wachtwoord, '')) < 10 then
    return jsonb_build_object('fout', 'Kies een wachtwoord van minstens 10 tekens.');
  end if;
  if (select count(*) from private.gebruikers where aangemaakt > now() - interval '1 hour') >= 30 then
    return jsonb_build_object('fout', 'Het is even te druk. Probeer het over een uur opnieuw.');
  end if;
  if exists (select 1 from private.gebruikers where naam = v_naam) then
    return jsonb_build_object('fout', 'Deze gebruikersnaam is al bezet.');
  end if;
  insert into private.gebruikers (naam, weergavenaam, hash, akkoord_op)
  values (v_naam, left(trim(coalesce(p_weergavenaam, '')), 60),
          extensions.crypt(p_wachtwoord, extensions.gen_salt('bf', 10)), now())
  returning id into v_id;
  insert into public.gegevens (id, data) values (v_id, '{}'::jsonb) on conflict (id) do nothing;
  return jsonb_build_object('ok', true, 'id', v_id);
end; $$;

-- --- Eigen gegevens ----------------------------------------------------------

create or replace function public.mijn_gegevens(p_naam text, p_wachtwoord text)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord);
begin
  if v_id is null then return jsonb_build_object('geen_toegang', true); end if;
  return jsonb_build_object(
    'data', (select data from public.gegevens where id = v_id),
    'gebruiker', (select jsonb_build_object('id', id, 'naam', naam, 'weergavenaam', private.weergave(id),
                                            'beheerder', id = 1)
                  from private.gebruikers where id = v_id));
end; $$;

create or replace function public.mijn_gegevens_bewaren(p_naam text, p_wachtwoord text, p_data jsonb)
returns boolean language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord);
begin
  if v_id is null then return false; end if;
  insert into public.gegevens (id, data) values (v_id, p_data)
  on conflict (id) do update set data = excluded.data;
  return true;
end; $$;

create or replace function public.profiel_bijwerken(p_naam text, p_wachtwoord text, p_nieuwe_naam text,
                                                    p_weergavenaam text, p_nieuw_wachtwoord text)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare
  v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord);
  v_naam text := nullif(lower(trim(coalesce(p_nieuwe_naam, ''))), '');
begin
  if v_id is null then return jsonb_build_object('geen_toegang', true); end if;
  if v_naam is not null then
    if v_naam !~ '^[a-z0-9_.-]{3,30}$' then
      return jsonb_build_object('fout', 'Gebruikersnaam: 3 tot 30 tekens, kleine letters, cijfers, punt of streepje.');
    end if;
    if exists (select 1 from private.gebruikers where naam = v_naam and id <> v_id) then
      return jsonb_build_object('fout', 'Deze gebruikersnaam is al bezet.');
    end if;
    update private.gebruikers set naam = v_naam where id = v_id;
  end if;
  if p_weergavenaam is not null then
    update private.gebruikers set weergavenaam = left(trim(p_weergavenaam), 60) where id = v_id;
  end if;
  if coalesce(p_nieuw_wachtwoord, '') <> '' then
    if length(p_nieuw_wachtwoord) < 10 then
      return jsonb_build_object('fout', 'Kies een wachtwoord van minstens 10 tekens.');
    end if;
    update private.gebruikers set hash = extensions.crypt(p_nieuw_wachtwoord, extensions.gen_salt('bf', 10))
    where id = v_id;
  end if;
  return jsonb_build_object('ok', true);
end; $$;

-- Recht op vergetelheid: gegevens leeg, aanbod offline, account onbruikbaar.
create or replace function public.account_verwijderen(p_naam text, p_wachtwoord text)
returns boolean language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord);
begin
  if v_id is null or v_id = 1 then return false; end if;
  update public.gegevens set data = '{}'::jsonb where id = v_id;
  update private.media set verwijderd = true, inhoud = ''::bytea where gebruiker_id = v_id;
  update private.aanbod set actief = false, omschrijving = '', contact = '' where gebruiker_id = v_id;
  update private.project_leden set actief = false where gebruiker_id = v_id;
  update private.gebruikers set verwijderd = true, naam = null, weergavenaam = 'Verwijderd account',
         hash = extensions.crypt(extensions.gen_random_uuid()::text, extensions.gen_salt('bf', 4))
  where id = v_id;
  return true;
end; $$;

-- --- Foto's en geluid (nu per gebruiker) ------------------------------------

create or replace function public.media_toevoegen(p_naam text, p_wachtwoord text, p_afspraak_id integer, p_soort text,
                                                  p_bestandsnaam text, p_mime text, p_inhoud text)
returns bigint language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord); nieuw bigint;
begin
  if v_id is null then return null; end if;
  if length(p_inhoud) > 14000000 then raise exception 'te groot'; end if;
  insert into private.media (gebruiker_id, afspraak_id, soort, naam, mime, inhoud)
  values (v_id, p_afspraak_id, p_soort, p_bestandsnaam, p_mime, decode(p_inhoud, 'base64'))
  returning id into nieuw;
  return nieuw;
end; $$;

create or replace function public.media_lijst(p_naam text, p_wachtwoord text, p_afspraak_id integer)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare v_id bigint := private.gebruiker_id(p_naam, p_wachtwoord);
begin
  if v_id is null then return jsonb_build_object('geen_toegang', true); end if;
  return jsonb_build_object('media', coalesce((
    select jsonb_agg(jsonb_build_object('id', id, 'soort', soort, 'naam', naam, 'mime', mime, 'aangemaakt', aangemaakt) order by id)
    from private.media where gebruiker_id = v_id and afspraak_id = p_afspraak_id and not verwijderd), '[]'::jsonb));
end; $$;

create or replace function public.media_ophalen(p_naam text, p_wachtwoord text, p_id bigint)
