"""Betaalde tickets, evenementenpagina en verlopen, bovenop de Studio-tickets. Geïsoleerde database, geen betaalprovider."""
import json,os,subprocess,unittest,uuid
from pathlib import Path
import test_studio_tickets as basis

MOCKS = """
create table private.winkels(gebruiker_id bigint primary key,naam text,open boolean default true);
create function private.winkel_kan_betalen(bigint)returns boolean language sql as $$select exists(select 1 from private.winkels where gebruiker_id=$1 and open)$$;
create table private.aanbod(id bigint generated by default as identity primary key,gebruiker_id bigint,soort text,titel text,omschrijving text,prijs numeric,plaats text,contact text,
 actief boolean default true,geblokkeerd boolean default false,betaalwijzen text[],levering text[],in_winkel boolean default false,voorraad integer);
create table private.bestellingen(id bigint generated by default as identity primary key,aanbod_id bigint,koper bigint,verkoper bigint,aantal integer default 1,status text);
"""


class EventBetaaldTests(basis.StudioTicketsTests):
    @classmethod
    def sql(cls, tekst, db=None):
        host = os.environ.get('ASSISTENT_TEST_PG_HOST')
        if not host:
            return super().sql(tekst, db)
        r = subprocess.run(['psql', '-h', host, '-p', os.environ.get('ASSISTENT_TEST_PG_PORT', '5432'), '-U', 'postgres', '-d', db or cls.db,
                            '-XqAt', '-v', 'ON_ERROR_STOP=1'], input=tekst, text=True, capture_output=True, timeout=30)
        if r.returncode:
            raise AssertionError(r.stderr)
        return r.stdout.strip()

    @classmethod
    def setUpClass(cls):
        # De basis maakt de database en laadt studio_tickets.sql; daarna komen webshop-nep en deze migratie.
        orig = Path.read_text
        def lezen(p, *a, **k):
            t = orig(p, *a, **k)
            return MOCKS + t if p.name == 'studio_tickets.sql' else t
        Path.read_text = lezen
        try:
            super().setUpClass()
        finally:
            Path.read_text = orig
        cls.sql(Path('sql/event_betaald.sql').read_text())

    def setUp(self):
        self.sql('truncate private.aanbod,private.bestellingen,private.winkels restart identity cascade')
        super().setUp()
        self.sql("insert into private.winkels values(1,'Gala BV',true)")

    def soort(self, prijs=25, aantal=100, who='host', event=10, ident='null'):
        return self.call('event_ticketsoort_bewaren', f"'{who}','test-only',{event},{ident},'Staanplaats',{prijs},{aantal},true")

    def kopen(self, aanbod, koper=2, aantal=2):
        return self.sql(f"insert into private.bestellingen(aanbod_id,koper,verkoper,aantal,status) values({aanbod},{koper},1,{aantal},'geaccepteerd') returning id")

    def test_paid_ticket_type_needs_manager_shop_and_valid_price(self):
        self.assertIn('fout', self.soort(who='gast'))
        self.assertIn('fout', self.soort(prijs=0))
        self.sql('update private.winkels set open=false')
        self.assertIn('Open eerst', self.soort()['fout'])
        self.sql('update private.winkels set open=true')
        r = self.soort()
        self.assertTrue(r['ok'])
        rij = self.sql(f"select titel,prijs,voorraad,in_winkel,levering::text,event_id from private.aanbod where id={r['id']}")
        self.assertEqual(rij, 'Staanplaats · Testevent|25.00|100|t|{ophalen}|10')

    def test_payment_issues_tickets_once_and_refund_revokes_unused(self):
        a = self.soort()['id']
        b = self.kopen(a, aantal=3)
        self.assertEqual(self.sql("select count(*) from private.event_tickets"), '0')
        self.sql(f"update private.bestellingen set status='betaald' where id={b}")
        self.sql(f"update private.bestellingen set status='betaald' where id={b}")
        self.assertEqual(self.sql(f"select count(*) from private.event_tickets where bestelling={b} and gebruiker=2"), '3')
        mijn = self.call('mijn_event_tickets', "'gast','test-only'")['tickets']
        self.assertEqual(len(mijn), 3)
        self.assertTrue(all(t['betaald'] for t in mijn))
        self.sql(f"update private.event_tickets set status='binnen' where id=(select id from private.event_tickets where bestelling={b} limit 1)")
        self.sql(f"update private.bestellingen set status='terugbetaald' where id={b}")
        self.assertEqual(self.sql(f"select string_agg(status,',' order by status) from private.event_tickets where bestelling={b}"), 'binnen,ingetrokken,ingetrokken')

    def test_paid_event_blocks_free_tickets_but_free_event_still_works(self):
        self.assertIn('id', self.issue())
        self.soort(event=11)
        self.assertIn('evenementenpagina', self.issue(event=11)['fout'])

    def test_events_page_shows_public_upcoming_events_with_types(self):
        self.soort()
        lijst = self.call('events_lijst', "'buiten','test-only',''")['events']
        self.assertEqual([e['id'] for e in lijst], [10])
        self.assertEqual(lijst[0]['soorten'][0]['titel'], 'Staanplaats')
        self.assertEqual(lijst[0]['organisator'], 'Gala BV')
        self.assertFalse(lijst[0]['gratis'])
        self.assertNotIn('code', json.dumps(lijst))
        self.assertEqual(self.call('events_lijst', "'buiten','test-only','gala'")['events'], [])
        self.assertIn('fout', self.call('event_bekijken', "'buiten','test-only',11"))

    def test_expired_events_leave_the_page_and_stop_selling(self):
        a = self.soort()['id']
        self.sql("update private.community_activiteiten set einde=now()-interval '1 minute' where id=10")
        self.assertEqual(self.call('events_lijst', "'buiten','test-only',''")['events'], [])
        self.assertIn('fout', self.call('event_bekijken', "'buiten','test-only',10"))
        self.sql('select private.events_verlopen()')
        self.assertEqual(self.sql(f'select actief,in_winkel from private.aanbod where id={a}'), 'f|f')
        self.assertEqual(self.sql('select open from private.event_ticketinstellingen where evenement=10'), 'f')
        self.assertEqual(self.sql('select count(*) from private.community_activiteiten where id=10 and not weg'), '1')


if __name__ == '__main__':
    unittest.main()
